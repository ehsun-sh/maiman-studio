# The closed form, which is what the implementation is checked against


def symbol_error_rate(bit_error_rate: float, bits_per_symbol: int = 8) -> float:
    """Probability a byte is wrong, given independent bit errors within it."""
    return 1.0 - (1.0 - bit_error_rate) ** bits_per_symbol


def output_bit_error_rate(input_bit_error_rate: float) -> float:
    """Post-decoding bit error rate, from the standard bounded-distance expression.

    A codeword is decoded wrongly when more than ``t`` of its 255 symbols are in
    error. The usual approximation then assumes such a codeword leaves ``i``
    symbols wrong — the ones that were already wrong — which gives::

        P_s,out = (1/n) * sum_{i=t+1}^{n} i * C(n, i) * p^i * (1-p)^(n-i)

    and a bit rate of ``P_s,out`` scaled by the fraction of bits a wrong byte
    carries. It is an approximation in one direction only: a miscorrecting
    decoder adds up to ``t`` further bad symbols, so the true rate is a little
    worse than this, never better. Quoting the optimistic bound and calling it
    the answer is the standard way to overstate a coding gain, so the direction
    is stated rather than left to be discovered.

    Independent bit errors are assumed. That is exactly the channel this library
    produces — additive noise on independent symbols — and exactly not the
    channel Reed-Solomon was chosen for, which is bursty. On a bursty channel
    this code does better than this expression says.
    """
    if not 0.0 <= input_bit_error_rate <= 1.0:
        raise ValueError(f"a bit error rate must be in [0, 1], got {input_bit_error_rate}")
    if input_bit_error_rate == 0.0:
        return 0.0

    p = symbol_error_rate(input_bit_error_rate)
    n = CODEWORD_SYMBOLS
    total = 0.0
    for i in range(CORRECTABLE_SYMBOLS + 1, n + 1):
        term = math.comb(n, i) * p**i * (1.0 - p) ** (n - i)
        total += i * term
        if term == 0.0 and i > CORRECTABLE_SYMBOLS + 8:
            break  # the tail has underflowed; the remaining terms are smaller
    symbols_out = total / n
    # How much of a wrong byte is wrong. Conditioned on at least one of its
    # eight bits having flipped, the expected number that did is ``8*p/p_s``, so
    # the fraction of the byte in error is ``p/p_s``. For the small p this is
    # used at that is about an eighth — a wrong byte is almost always wrong in
    # exactly one bit — and *not* the half it would tend to if p approached 0.5.
    # Assuming the half instead makes this four times pessimistic at 3e-3, which
    # is what the Monte Carlo comparison in the tests was written to catch and
    # did.
    #
    # The message rate and the codeword rate are the same number here: the i bad
    # symbols of a failed codeword fall uniformly across all 255 positions, so
    # the 239/255 that reach the message cancels against the 239 it is divided
    # by.
    return symbols_out * bit_error_rate_ratio(input_bit_error_rate)


def bit_error_rate_ratio(input_bit_error_rate: float) -> float:
    """Fraction of a symbol that is wrong, given that the symbol is wrong."""
    p = input_bit_error_rate
    p_s = symbol_error_rate(p)
    return p / p_s if p_s > 0.0 else 0.0


def overhead() -> float:
    """Fractional rate cost of the code: 6.69 % for RS(255, 239)."""
    return CODEWORD_SYMBOLS / MESSAGE_SYMBOLS - 1.0
